function readLanguage(): Language {
  try {
    return window.localStorage.getItem(STORAGE_KEY) === 'en-US' ? 'en-US' : 'zh-CN'
  } catch {
    return 'zh-CN'
  }
}

let language: Language = typeof window === 'undefined' ? 'zh-CN' : readLanguage()

export function getLanguage(): Language { return language }

export function setLanguage(next: Language): Language {
  language = next === 'en-US' ? 'en-US' : 'zh-CN'
  try { window.localStorage.setItem(STORAGE_KEY, language) } catch { /* local storage may be unavailable */ }
  if (typeof window !== 'undefined') window.dispatchEvent(new CustomEvent(LANGUAGE_EVENT, { detail: language }))
  return language
}

export function toggleLanguage(): Language { return setLanguage(language === 'zh-CN' ? 'en-US' : 'zh-CN') }

export function t(key: string, selected = language): string {
  return COPY[selected][key] ?? COPY['zh-CN'][key] ?? key
}
